/**
 * Downloads Google Places photos into public/places/{id}.jpg
 * and writes src/lib/data/place-photo-urls.ts
 *
 * Usage: node scripts/fetch-place-photos.mjs
 * Requires GOOGLE_PLACES_API_KEY in .env.local
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outDir = path.join(root, "public/places");
const envPath = path.join(root, ".env.local");

function loadEnv() {
  if (!fs.existsSync(envPath)) return {};
  const env = {};
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const m = line.match(/^([A-Z_]+)=(.*)$/);
    if (m) env[m[1]] = m[2].trim();
  }
  return env;
}

const MOMBASA = { latitude: -4.0435, longitude: 39.6682 };

/** id, search query, optional pinned Google place id (ChIJ…) */
const TARGETS = JSON.parse(
  fs.readFileSync(path.join(__dirname, "place-photo-targets.json"), "utf8"),
);

async function searchPlaceId(apiKey, query) {
  const res = await fetch("https://places.googleapis.com/v1/places:searchText", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-Goog-Api-Key": apiKey,
      "X-Goog-FieldMask":
        "places.id,places.displayName,places.photos,places.userRatingCount",
    },
    body: JSON.stringify({
      textQuery: query,
      regionCode: "KE",
      locationBias: {
        circle: { center: MOMBASA, radius: 50000 },
      },
      maxResultCount: 3,
    }),
  });
  if (!res.ok) {
    console.warn("search fail", query, res.status, await res.text());
    return null;
  }
  const json = await res.json();
  const places = json.places ?? [];
  if (places.length === 0) return null;
  places.sort(
    (a, b) => (b.userRatingCount ?? 0) - (a.userRatingCount ?? 0),
  );
  return places[0];
}

async function getPlaceWithPhotos(apiKey, placeId) {
  const id = placeId.replace(/^places\//, "");
  const res = await fetch(`https://places.googleapis.com/v1/places/${id}`, {
    headers: {
      "X-Goog-Api-Key": apiKey,
      "X-Goog-FieldMask": "id,displayName,photos",
    },
  });
  if (!res.ok) return null;
  return res.json();
}

async function downloadPhoto(apiKey, photoName, destPath) {
  const url = `https://places.googleapis.com/v1/${photoName}/media?maxWidthPx=1200&skipHttpRedirect=true`;
  const meta = await fetch(url, {
    headers: {
      "X-Goog-Api-Key": apiKey,
    },
  });
  if (!meta.ok) {
    console.warn("photo meta fail", meta.status);
    return false;
  }
  const { photoUri } = await meta.json();
  if (!photoUri) return false;
  const img = await fetch(photoUri);
  if (!img.ok) return false;
  const buf = Buffer.from(await img.arrayBuffer());
  if (buf.length < 2000) return false;
  fs.writeFileSync(destPath, buf);
  return true;
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function main() {
  const env = loadEnv();
  const apiKey = env.GOOGLE_PLACES_API_KEY;
  if (!apiKey) {
    console.error("Missing GOOGLE_PLACES_API_KEY in .env.local");
    process.exit(1);
  }

  fs.mkdirSync(outDir, { recursive: true });

  const mapping = {};
  const log = [];

  for (const target of TARGETS) {
    const dest = path.join(outDir, `${target.id}.jpg`);
    process.stdout.write(`→ ${target.id} … `);

    try {
      let place = null;
      if (target.placeId) {
        place = await getPlaceWithPhotos(apiKey, target.placeId);
      }
      if (!place?.photos?.length) {
        const hit = await searchPlaceId(apiKey, target.query);
        if (hit?.id) {
          place = hit.photos?.length
            ? hit
            : await getPlaceWithPhotos(apiKey, hit.id);
        }
      }

      const photoName = place?.photos?.[0]?.name;
      if (!photoName) {
        console.log("no photo");
        log.push({ id: target.id, ok: false, reason: "no photo" });
        await sleep(350);
        continue;
      }

      const ok = await downloadPhoto(apiKey, photoName, dest);
      if (ok) {
        mapping[target.id] = `/places/${target.id}.jpg`;
        console.log("saved");
        log.push({
          id: target.id,
          ok: true,
          name: place.displayName?.text,
        });
      } else {
        console.log("download failed");
        log.push({ id: target.id, ok: false, reason: "download" });
      }
    } catch (e) {
      console.log("error", e.message);
      log.push({ id: target.id, ok: false, reason: String(e.message) });
    }
    await sleep(400);
  }

  const tsOut = path.join(root, "src/lib/data/place-photo-urls.ts");
  const lines = [
    "/** Auto-generated by scripts/fetch-place-photos.mjs — do not edit by hand. */",
    "export const PLACE_PHOTO_URLS: Record<string, string> = {",
    ...Object.entries(mapping).map(
      ([id, url]) => `  "${id}": "${url}",`,
    ),
    "};",
    "",
    "export function placePhoto(id: string, fallback: string): string {",
    "  return PLACE_PHOTO_URLS[id] ?? fallback;",
    "}",
    "",
  ];
  fs.writeFileSync(tsOut, lines.join("\n"));
  fs.writeFileSync(
    path.join(__dirname, "place-photo-fetch-log.json"),
    JSON.stringify({ at: new Date().toISOString(), log }, null, 2),
  );
  console.log(`\nWrote ${Object.keys(mapping).length} photos → public/places/`);
  console.log(`Updated ${tsOut}`);
}

main();
